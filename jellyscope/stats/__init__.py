"""Statistiky - vsechny otazky, ktere klademe databazi.

Kazda funkce tady dela jednu vec: polozi jeden SQL dotaz a vrati vysledek
jako obycejny seznam slovniku. Zadna funkce nic nekresli a nic nezapisuje.

Tohle rozdeleni ("odkud data" / "co s nimi" / "jak vypadaji") je ta nejlepsi
navykovka, kterou si z projektu muzes odnest. Kdyz se pak nekde objevi
spatne cislo, vis presne, ve kterem ze tri souboru hledat.

Poznamka k casu: cas ukladame v UTC, ale pro cloveka ho prevadime na mistni
cas modifikatorem 'localtime'. "Nejaktivnejsi hodina" musi odpovidat hodinam
na hodinach na zdi, ne v Greenwichi.

Balík podle témat (jellyscope/stats/):

* `obdobi` - Časová okna statistik: období, jeho meze a předchozí období ke srovnání.
* `druhy` - Druhy obsahu (filmy, seriály, ostatní) a jak se jmenují typy položek.
* `prehled` - Souhrn období: přehled, srovnání dvou období, sledovanost po dnech, způsoby přehrání, přehrávače, heatmapa.
* `prehravani` - Co se hraje právě teď a popis přepočtu (transcode).
* `nedavno` - Nedávno přidané tituly a dávky dílů.
* `tituly` - Seskupení přehrání do titulů (seriál, film) a nejsledovanější tituly.
* `divaci` - Diváci: souhrny po divácích, tabulka diváků, detail diváka.
* `historie` - Historie přehrání: filtry, stránka a API.
* `technika` - Technika knihovny: rozlišení, kodeky, dynamický rozsah.
* `rust` - Stav a růst knihovny v čase (snímky, dopočtená křivka).
* `knihovna` - Knihovna po titulech: řádky, detail seriálu, dlaždice a aktivita knihovny.
* `polozka` - Detail jedné položky: verze, stopy, přehrání, sourozenci, smazání.
* `archiv` - Archiv: archivované položky, hledání mezi existujícími a přiřazení k jinému titulu.
* `sit` - Síť: kolik toho teklo k přehrávačům, špičky a živý tok.
* `odkud` - Odkud se dívají: domácí síť nebo internet, místa a země diváků.

Zvenku se volá jako dřív (`stats.top_items(...)`, `from .stats import _meze`):
tenhle soubor vystaví všechno, co dřív bylo v jednom stats.py. Testy, které
jméno podvrhují a čekají účinek uvnitř balíku, ho podvrhují v podmodulu
(tests/test_stats_balik.py, kontrola e)."""

